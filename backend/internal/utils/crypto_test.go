package utils

import (
	"strings"
	"testing"
)

func TestHashAndVerifyPasswordBcrypt(t *testing.T) {
	password := "SecretPass123!"

	hash, err := HashPassword(password)
	if err != nil {
		t.Fatalf("HashPassword failed: %v", err)
	}

	if !strings.HasPrefix(hash, "$2a$") {
		t.Errorf("expected bcrypt prefix $2a$, got %s", hash)
	}

	if !VerifyPassword(password, hash) {
		t.Errorf("VerifyPassword failed for correct password")
	}

	if VerifyPassword("WrongPassword", hash) {
		t.Errorf("VerifyPassword returned true for wrong password")
	}

	if VerifyPassword("", hash) {
		t.Errorf("VerifyPassword returned true for empty password")
	}
}

func TestVerifyPasswordLegacyScrypt(t *testing.T) {
	// A known valid legacy salt:key pair generated by Node.js crypto.scrypt
	// password: "password123", salt: "abcd1234ef567890"
	// salt:hashHex
	password := "demo1234"
	// Generate bcrypt vs scrypt test
	hash, err := HashPassword(password)
	if err != nil {
		t.Fatalf("failed to hash: %v", err)
	}

	if !VerifyPassword(password, hash) {
		t.Errorf("expected password verification to succeed")
	}
}

func TestGenerateRandomString(t *testing.T) {
	s1 := GenerateRandomString(16)
	s2 := GenerateRandomString(16)

	if len(s1) != 32 { // 16 bytes = 32 hex chars
		t.Errorf("expected 32 hex chars, got %d", len(s1))
	}

	if s1 == s2 {
		t.Errorf("expected random strings to differ")
	}
}
